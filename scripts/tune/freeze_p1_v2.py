"""Freeze the P1 settings of the v2 backbone from the p1tune_v2 studies. Mac only.

    python scripts/tune/freeze_p1_v2.py

Reads ``results/tuning/tuning_v2_P1_a<anchor>.json`` (written by the cluster stage p1tune_v2). Each must hold the
configured number of COMPLETE trials, the backbone options of ``configs/tuned_v2.yaml`` and the epoch limit
``nrp.P1_EPOCHS`` with the configured patience. Writes ``write_result("tuning_p1_v2_summary")`` from a clean tree, then
``configs/tuned_p1_v2.yaml``, which the stages p1v2b and pcompv2b read: the best parameters per anchor under ``P1``,
``arch``, ``max_epochs`` and ``patience``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

sys.path.insert(0, str(Path(__file__).resolve().parent))
from freeze import PARAM_ORDER


def main() -> None:
    import yaml

    from dftgnn.config import load_config
    from dftgnn.io.results import write_result
    from dftgnn.train import code_sha
    from dftgnn.train import nrp as NRP

    cfg = load_config()
    arch = yaml.safe_load(NRP.TUNED_V2.read_text())["arch"]
    epochs = (NRP.P1_EPOCHS, cfg.training.early_stopping.patience)
    studies = {}
    for a in cfg.tuning.anchors:
        pay = json.loads((ROOT / "results" / "tuning" / f"tuning_v2_P1_a{a}.json").read_text())["payload"]
        if pay["n_complete"] != cfg.tuning.optuna_trials_per_model_per_anchor:
            raise SystemExit(f"v2_P1_a{a}: {pay['n_complete']} complete trials")
        if pay.get("arch") != arch:
            raise SystemExit(f"v2_P1_a{a}: arch {pay.get('arch')} != {arch}")
        if (pay["max_epochs"], pay["patience"]) != epochs:
            raise SystemExit(f"v2_P1_a{a}: max_epochs, patience {pay['max_epochs']}, {pay['patience']} != {epochs}")
        studies[a] = pay
    summary = {"arch": arch, "max_epochs": epochs[0], "patience": epochs[1],
               "best": {f"P1|{a}": {"best_value": p["best_value"], "best_trial": p["best_trial"],
                                    "best_params": p["best_params"], "top5_spread": p["top5_spread"],
                                    "trials_reaching_cap": len(p["trials_reaching_cap"])}
                        for a, p in studies.items()},
               "tuned_file": "configs/tuned_p1_v2.yaml"}
    print(write_result("tuning_p1_v2_summary", summary, config=cfg))

    def flow(d: dict) -> str:            # exact float round-trip, as in freeze.py
        return yaml.safe_dump(d, default_flow_style=True, sort_keys=False, width=1000).strip()

    lines = ["# P1 settings of the v2 backbone (docs/deviations.md, 2026-10-19). Generated by scripts/tune/freeze_p1_v2.py",
             "# from results/tuning/tuning_v2_P1_a<anchor>.json (stage p1tune_v2, 30 COMPLETE trials per study).",
             f"# Freeze commit: {code_sha()}. Do not edit by hand.",
             "version: tuned-p1-v2", f"arch: {flow(dict(arch))}",
             f"max_epochs: {epochs[0]}", f"patience: {epochs[1]}", "models:", "  P1:"]
    for a in cfg.tuning.anchors:
        p = studies[a]["best_params"]
        lines.append(f"    {a}: {flow({k: p[k] for k in PARAM_ORDER})}")
    NRP.TUNED_P1_V2.write_text("\n".join(lines) + "\n")
    back = yaml.safe_load(NRP.TUNED_P1_V2.read_text())
    for a, pay in studies.items():
        if back["models"]["P1"][a] != pay["best_params"]:
            raise SystemExit(f"P1 a{a}: written values do not round-trip")
    if back["arch"] != arch:
        raise SystemExit("arch does not round-trip")
    print(NRP.TUNED_P1_V2)


if __name__ == "__main__":
    main()
