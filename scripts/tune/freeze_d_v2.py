"""Freeze the D settings of the v2 backbone from the dtune_v2 studies. Mac only.

    python scripts/tune/freeze_d_v2.py

Reads ``results/tuning/tuning_v2_D_a<anchor>.json`` (written by the cluster stage dtune_v2). Each must hold the
configured number of COMPLETE trials, the backbone options of ``configs/tuned_v2.yaml``, the epoch limit
``nrp.D_EPOCHS`` with the configured patience, and the search space of ``nrp.dtune_space``. Writes
``write_result("tuning_d_v2_summary")`` from a clean tree, then ``configs/tuned_d_v2.yaml``, which the stage
dretrain_v2 reads: the best parameters per anchor under ``D`` (the injection variant included), ``arch``,
``max_epochs`` and ``patience``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

sys.path.insert(0, str(Path(__file__).resolve().parent))
from freeze import PARAM_ORDER


def freeze(records_dir: Path, out: Path, cfg, write_summary, freeze_commit: str) -> dict:
    """Check the three records in ``records_dir``, write the summary with ``write_summary(name, payload)`` and the
    config to ``out``; return the studies' payloads by anchor."""
    import yaml

    from dftgnn.train import nrp as NRP

    arch = yaml.safe_load(NRP.TUNED_V2.read_text())["arch"]
    epochs = (NRP.D_EPOCHS, cfg.training.early_stopping.patience)
    space = NRP.dtune_space(cfg)
    order = (*PARAM_ORDER, *(k for k in space if k not in PARAM_ORDER))
    studies = {}
    for a in cfg.tuning.anchors:
        pay = json.loads((Path(records_dir) / f"tuning_v2_D_a{a}.json").read_text())["payload"]
        if pay["n_complete"] != cfg.tuning.optuna_trials_per_model_per_anchor:
            raise SystemExit(f"v2_D_a{a}: {pay['n_complete']} complete trials")
        if pay.get("arch") != arch:
            raise SystemExit(f"v2_D_a{a}: arch {pay.get('arch')} != {arch}")
        if (pay["max_epochs"], pay["patience"]) != epochs:
            raise SystemExit(f"v2_D_a{a}: max_epochs, patience {pay['max_epochs']}, {pay['patience']} != {epochs}")
        if pay.get("search_space") != space:
            raise SystemExit(f"v2_D_a{a}: search space differs from nrp.dtune_space")
        if set(pay["best_params"]) != set(order) or pay["best_model"] != pay["best_params"]["injection"]:
            raise SystemExit(f"v2_D_a{a}: best parameters {sorted(pay['best_params'])} do not match the space")
        studies[a] = pay
    summary = {"arch": arch, "max_epochs": epochs[0], "patience": epochs[1], "search_space": space,
               "best": {f"D|{a}": {"best_value": p["best_value"], "best_trial": p["best_trial"],
                                   "best_model": p["best_model"], "best_params": p["best_params"],
                                   "top5_spread": p["top5_spread"],
                                   "trials_reaching_cap": len(p["trials_reaching_cap"])}
                        for a, p in studies.items()},
               "tuned_file": "configs/tuned_d_v2.yaml"}
    print(write_summary("tuning_d_v2_summary", summary))

    def flow(d: dict) -> str:            # exact float round-trip, as in freeze.py
        return yaml.safe_dump(d, default_flow_style=True, sort_keys=False, width=1000).strip()

    lines = ["# D settings of the v2 backbone (docs/deviations.md, 2026-10-23). Generated by scripts/tune/freeze_d_v2.py",
             "# from results/tuning/tuning_v2_D_a<anchor>.json (stage dtune_v2, 30 COMPLETE trials per study).",
             f"# Freeze commit: {freeze_commit}. Do not edit by hand.",
             "version: tuned-d-v2", f"arch: {flow(dict(arch))}",
             f"max_epochs: {epochs[0]}", f"patience: {epochs[1]}", "models:", "  D:"]
    for a in cfg.tuning.anchors:
        p = studies[a]["best_params"]
        lines.append(f"    {a}: {flow({k: p[k] for k in order})}")
    out = Path(out)
    out.write_text("\n".join(lines) + "\n")
    back = yaml.safe_load(out.read_text())
    for a, pay in studies.items():
        if back["models"]["D"][a] != pay["best_params"]:
            raise SystemExit(f"D a{a}: written values do not round-trip")
    if back["arch"] != arch:
        raise SystemExit("arch does not round-trip")
    return studies


def main() -> None:
    from dftgnn.config import load_config
    from dftgnn.io.results import write_result
    from dftgnn.train import code_sha
    from dftgnn.train import nrp as NRP

    cfg = load_config()
    freeze(ROOT / "results" / "tuning", NRP.TUNED_D_V2, cfg,
           lambda name, pay: write_result(name, pay, config=cfg), code_sha())
    print(NRP.TUNED_D_V2)


if __name__ == "__main__":
    main()
